-- Create the drop for a spray (null when picking is off or the share is under one note).
create or replace function public.bl_money_drop_create(p_uid uuid, p_loc text, p_amount bigint, p_vip boolean)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_note  bigint := greatest(1, floor(bl_spray_num('club.pick_note', 10000)))::bigint;
  v_pct   numeric := least(100, greatest(0, bl_spray_num('club.pick_pct', 20)));
  v_secs  numeric := least(30, greatest(1, bl_spray_num('club.pick_seconds', 5)));
  v_total numeric;
  v_now   timestamptz := bl_now();
  d       money_drops;
begin
  if not coalesce(bl_cfg_bool('club.pick_enabled'), true) or coalesce(p_amount, 0) <= 0 then
    return null;
  end if;
  v_total := floor(p_amount::numeric * v_pct / 100);
  if v_total < v_note then
    return null;
  end if;
  insert into money_drops (location_id, sprayer, username, total, remaining, note, vip, self_ok, created_at, expires_at)
  values (p_loc, p_uid, (select username from profiles where id = p_uid), v_total::bigint, v_total::bigint, v_note,
          coalesce(p_vip, false), coalesce(bl_cfg_bool('club.pick_self'), false), v_now, v_now + make_interval(secs => v_secs))
  returning * into d;
  return to_jsonb(d) || jsonb_build_object('notes', d.remaining / d.note, 'ms_left', round(v_secs * 1000));
end $$;

-- An MC line from a pool with {user} {amount} {place} filled (fallback when the pool is empty).
create or replace function public.bl_money_pick_line(p_loc text, p_kind text, p_user text, p_amount bigint, p_place text, p_fallback text)
returns text
language plpgsql security definer set search_path = public as $$
declare t hype_templates;
begin
  t := bl_hype_pick(p_loc, p_kind);
  if t.id is null then
    return p_fallback;
  end if;
  return bl_hype_render(replace(t.line, '{user}', coalesce(p_user, '')), p_user, p_place, 1, coalesce(p_amount, 0));
end $$;

-- Settle a drop once (locked by the caller): the top picker shout-out.
create or replace function public.bl_money_drop_settle(p_drop bigint)
returns void
language plpgsql security definer set search_path = public as $$
declare
  d       money_drops;
  k       record;
  v_place text;
begin
  update money_drops set settled = true where id = p_drop and not settled returning * into d;
  if not found or not coalesce(bl_cfg_bool('club.pick_summary'), true) then
    return;
  end if;
  select pk.user_id, pk.amount, pr.username into k
    from money_drop_picks pk join profiles pr on pr.id = pk.user_id
   where pk.drop_id = p_drop and pk.amount > 0
   order by pk.amount desc, pk.first_at asc limit 1;
  if not found then
    return;
  end if;
  select regexp_replace(name, '\s*\(.*\)\s*$', '') into v_place from locations where id = d.location_id;
  insert into place_announcements (location_id, user_id, username, kind, amount, qty, text, ticker, global, place, vip)
  values (d.location_id, k.user_id, k.username, 'pick_top', k.amount, 1,
          left(bl_money_pick_line(d.location_id, 'pick_top', k.username, k.amount, v_place,
                                  format('@%s picked %s!', k.username, bl_naira(k.amount))), 400),
          null, false, v_place, d.vip);
end $$;

revoke all on function public.bl_money_drop_create(uuid, text, bigint, boolean) from public, anon, authenticated;
revoke all on function public.bl_money_pick_line(text, text, text, bigint, text, text) from public, anon, authenticated;
revoke all on function public.bl_money_drop_settle(bigint) from public, anon, authenticated;

-- ---------------------------------------------------------------------
-- 5. Pick (batched taps)
-- ---------------------------------------------------------------------
create or replace function public.money_pick(p_drop bigint, p_taps int)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_me     profiles := bl_me();
  d        money_drops;
  pk       money_drop_picks;
  v_now    timestamptz := bl_now();
  v_grace  numeric := least(10, greatest(0, bl_spray_num('club.pick_grace_s', 1.5)));
  v_rate   numeric := greatest(1, bl_spray_num('club.pick_max_taps_per_sec', 12));
  v_cap    int := greatest(1, floor(bl_spray_num('club.pick_max_per_player', 50)))::int;
  v_elapse numeric;
  v_allow  int;
  v_n      int := 0;
  v_amt    bigint := 0;
  v_cash   bigint;
  v_place  text;
  v_first  boolean := false;
  v_row    place_announcements;
begin
  if not coalesce(bl_cfg_bool('club.pick_enabled'), true) then
    raise exception 'Picking money is paused right now.' using errcode = 'P0001', hint = 'disabled';
  end if;
  if p_taps is null or p_taps < 0 or p_taps > 1000 then
    raise exception 'Wrong number of taps.' using errcode = 'P0001', hint = 'bad_taps';
  end if;
  -- the drop is THE lock: every pick on it runs one after the other, so the pool never goes below zero
  select * into d from money_drops where id = p_drop for update;
  if not found then
    raise exception 'That money don finish.' using errcode = 'P0001', hint = 'no_drop';
  end if;
  select regexp_replace(name, '\s*\(.*\)\s*$', '') into v_place from locations where id = d.location_id;
  select * into pk from money_drop_picks where drop_id = d.id and user_id = v_me.id;

  -- ended (past the grace): no error, just settle and say so
  if v_now > d.expires_at + make_interval(secs => v_grace) then
    if not d.settled then
      perform bl_money_drop_settle(d.id);
    end if;
    return jsonb_build_object('drop', d.id, 'picked', 0, 'taps', 0, 'expired', true, 'remaining', d.remaining,
      'notes_left', d.remaining / d.note, 'my_taps', coalesce(pk.taps, 0), 'my_total', coalesce(pk.amount, 0),
      'cash_after', v_me.cash);
  end if;

  if v_me.jailed_until is not null and v_me.jailed_until > v_now then
    raise exception 'You are in a police cell. No picking money from there.' using errcode = 'P0001', hint = 'jailed';
  end if;
  if v_me.hospitalized_until is not null and v_me.hospitalized_until > v_now then
    raise exception 'You are still admitted in hospital.' using errcode = 'P0001', hint = 'hospitalized';
  end if;
  if v_me.travel_to is not null then
    raise exception 'You are on the road. The money stays in the club.' using errcode = 'P0001', hint = 'traveling';
  end if;
  if v_me.location_id is distinct from d.location_id then
    raise exception 'You are not at % anymore.', coalesce(v_place, 'the club') using errcode = 'P0001', hint = 'wrong_place';
  end if;
  if d.sprayer = v_me.id and not d.self_ok then
    raise exception 'Na your own money! Let others pick am.' using errcode = 'P0001', hint = 'own_drop';
  end if;

  -- allowance: rate x time since the drop (+ half a second), capped per player per drop
  v_elapse := greatest(0, extract(epoch from v_now - d.created_at));
  v_allow := least(v_cap, floor((v_elapse + 0.5) * v_rate))::int;
  v_n := least(p_taps::bigint, greatest(0, v_allow - coalesce(pk.taps, 0))::bigint, d.remaining / d.note)::int;

  if v_n > 0 then
    v_amt := v_n::bigint * d.note;
    update money_drops set remaining = remaining - v_amt where id = d.id returning * into d;
    insert into money_drop_picks (drop_id, user_id, taps, amount, first_at, last_at)
    values (d.id, v_me.id, v_n, v_amt, v_now, v_now)
    on conflict (drop_id, user_id) do update
      set taps = money_drop_picks.taps + excluded.taps, amount = money_drop_picks.amount + excluded.amount,
          first_at = coalesce(money_drop_picks.first_at, excluded.first_at), last_at = excluded.last_at
    returning * into pk;
    v_cash := bl_add_money(v_me.id, 'cash', v_amt, 'money_pick',
                jsonb_build_object('location', d.location_id, 'place', v_place, 'drop', d.id, 'notes', v_n));
    -- first pick of this player in this drop: tell the club (once)
    if not pk.announced then
      update money_drop_picks set announced = true where drop_id = d.id and user_id = v_me.id;
      v_first := true;
      insert into place_announcements (location_id, user_id, username, kind, amount, qty, text, ticker, global, place, vip)
      values (d.location_id, v_me.id, v_me.username, 'pick', v_amt, 1,
              left(bl_money_pick_line(d.location_id, 'pick', v_me.username, v_amt, v_place,
                                      format('@%s is picking money! 💸', v_me.username)), 400),
              null, false, v_place, d.vip)
      returning * into v_row;
    end if;
    -- the floor is clean: settle now
    if d.remaining < d.note then
      perform bl_money_drop_settle(d.id);
    end if;
  else
    v_cash := v_me.cash;
  end if;

  return jsonb_build_object('drop', d.id, 'picked', v_amt, 'taps', v_n, 'asked', p_taps, 'capped', v_n < p_taps,
    'expired', false, 'empty', d.remaining < d.note, 'remaining', d.remaining, 'notes_left', d.remaining / d.note,
    'my_taps', coalesce(pk.taps, 0), 'my_total', coalesce(pk.amount, 0), 'cash_after', v_cash,
    'first', v_first, 'hype', case when v_row.id is null then null else to_jsonb(v_row) end);
end $$;
revoke all on function public.money_pick(bigint, int) from public, anon;
grant execute on function public.money_pick(bigint, int) to authenticated, service_role;

-- Active drops at a club (server clock), for the poll fallback and players who walk in mid-drop.
create or replace function public.money_drops_live(p_location text)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_uid uuid := bl_require_uid();
  v_now timestamptz := bl_now();
begin
  return jsonb_build_object(
    'enabled', coalesce(bl_cfg_bool('club.pick_enabled'), true),
    'poll_s', least(60, greatest(1, bl_spray_num('club.pick_poll_s', 3))),
    'drops', coalesce((
      select jsonb_agg(to_jsonb(d) || jsonb_build_object(
               'notes', d.remaining / d.note,
               'ms_left', greatest(0, round(extract(epoch from d.expires_at - v_now) * 1000)),
               'my_total', coalesce((select amount from money_drop_picks where drop_id = d.id and user_id = v_uid), 0))
             order by d.id)
        from money_drops d
       where d.location_id = p_location and d.expires_at > v_now and d.created_at > v_now - interval '1 minute'), '[]'::jsonb));
end $$;
revoke all on function public.money_drops_live(text) from public, anon;
grant execute on function public.money_drops_live(text) to authenticated, service_role;

-- ---------------------------------------------------------------------
-- 6. spray_custom creates the drop (guarded replacement of the live function)
-- ---------------------------------------------------------------------
do $$
declare
  v_def    text;
  v_anchor text := '''cooldown_s'', v_cd, ''effects'', v_eff, ''hype'', case';
begin
  select pg_get_functiondef('public.spray_custom(text,numeric,boolean)'::regprocedure) into v_def;
  if position('bl_money_drop_create' in v_def) > 0 then
    return;
  end if;
  if position(v_anchor in v_def) = 0 then
    raise exception 'SP2: spray_custom() changed; update the money pick migration anchor.';
  end if;
  v_def := replace(v_def, v_anchor,
    '''cooldown_s'', v_cd, ''effects'', v_eff, ''drop'', bl_money_drop_create(v_me.id, l.id, v_amt, v_vip), ''hype'', case');
  execute v_def;
end $$;
revoke all on function public.spray_custom(text, numeric, boolean) from public, anon;
grant execute on function public.spray_custom(text, numeric, boolean) to authenticated, service_role;

