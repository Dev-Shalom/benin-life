-- SP2 Pick the money (docs/SPRAY.md "Pick the money"). Every spray drops part of the money on the floor for the
-- other players in the club to tap up.
-- * Drop: spray_custom (normal and VIP) creates a money_drops row worth club.pick_pct (20 %) of the sprayed amount.
--   It comes OUT of the sprayed money: the sprayer pays nothing extra, the other 80 % still leaves the economy and
--   whatever nobody picks vanishes too. A drop lives club.pick_seconds (5 s) from created_at (bl_now). No drop when
--   the share is under one note (club.pick_note, ₦10,000). Drops can overlap.
-- * money_pick(p_drop, p_taps): the client batches taps (~every 300 ms). The player must stand in that club (not on
--   the road, not in a cell, not in hospital); the sprayer cannot pick their own drop (club.pick_self). The drop row
--   is locked FOR UPDATE, so two players racing can never take the pool below zero. Credits
--   min(taps, rate allowance, notes left) notes to CASH: the allowance is floor((seconds since the drop + 0.5) x
--   club.pick_max_taps_per_sec) taps in total, capped at club.pick_max_per_player per drop. A late batch is accepted
--   for club.pick_grace_s (1.5 s) after expiry, then it returns expired (no error) and settles the drop. Ledger
--   reason money_pick ("Picked money at <club>").
-- * Announcements (place_announcements, the existing hype broadcast + F1 poll path): a player's first pick in a drop
--   writes kind 'pick' ("@name is picking money! 💸" + an MC line from the new non-repeating pool 'pick', {user}),
--   once per player per drop. When the drop is settled (pool empty, or the first call after it ended) one summary
--   line kind 'pick_top' ("@top picked ₦X", pool 'pick_top') if club.pick_summary is on.
-- * money_drops_live(p_location): active drops at a club with ms_left (server clock) for the poll fallback and for
--   players who walk in mid-drop. money_drops is readable (RLS) and published for Realtime.
-- Guarded replacements of live functions (pg_get_functiondef): spray_custom, bl_ledger_label. Idempotent, safe on a
-- non-empty DB.

